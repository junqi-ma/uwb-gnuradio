// ---------------------------------------------------------------------------
// 13. gain-fit conditioning indicator (Householder QR; cond2(A) of the design)
// ---------------------------------------------------------------------------
// The final gain fit solves the M x K least squares with a Householder QR and
// reports `gain_condition` = cond2(A), computed from the singular values of the
// K x K factor R (A = QR).  It must stay finite, >= 1 and below the commit
// ceiling; the solve must still produce a committed, model-matching
// reconstruction.  A single fitted column is the sharpest pin: R is 1x1, so
// cond2(A) == 1 exactly.
BOOST_AUTO_TEST_CASE(test_sic_core_gain_condition_semantics)
{
    const std::vector<Path> paths = {
        { 0.0, cplx(1.f, 0.f) },
        { 7.0, cplx(0.f, 0.5f) },
        { 23.0, cplx(0.276f, -0.116f) },
        { 51.0, cplx(0.2f, 0.f) },
    };
    for (size_t K : { 1u, 4u }) {
        Fixture f = make_fixture(10, 32, static_cast<int64_t>(kPre), 64, 64, K, 8, 8,
                                 100);
        Signal s = build_signal(f.model, f.n, f.comm_start, paths, 0.0, kQaNoise,
                                900 + K);
        SicResult r = run(f, s);
        const double e = nmse(s.i, f.ihat, 0, f.n);
        std::printf("[sic-qa] gain-cond K=%zu state=%s n_paths=%zu cond=%.6f "
                    "res=%.4f NMSE=%.3e\n",
                    K, state_name(r.state), r.n_paths, r.gain_condition,
                    r.residual_corr, e);
        BOOST_CHECK_EQUAL(static_cast<int>(r.state),
                          static_cast<int>(SicState::Committed));
        BOOST_CHECK(std::isfinite(r.gain_condition));
        BOOST_CHECK_GE(r.gain_condition, 1.0 - 1e-9);
        BOOST_CHECK_LT(r.gain_condition, 1e6);
        BOOST_CHECK(std::isfinite(r.residual_corr));
        BOOST_CHECK_LT(r.residual_corr, f.cfg.validate_threshold);
        if (K == 1) {
            BOOST_CHECK_SMALL(r.gain_condition - 1.0, 1e-9);
            BOOST_CHECK_EQUAL(r.n_paths, size_t(1));
        } else {
            BOOST_CHECK_GE(r.n_paths, size_t(4));
            BOOST_CHECK_LT(e, 0.02);
        }
    }
}


// ---------------------------------------------------------------------------
// 17. reconstruction window low edge for a negative relative delay (F7)
// ---------------------------------------------------------------------------
// path_select returns paths magnitude-sorted, so tau_abs[0] is not necessarily
// the smallest delay; the reconstruction window must start at the earliest
// SELECTED delay (union_lo = min_k floor(tau_k)), matching the reference, which
// builds i_hat over the full window.  Two paths a few samples apart with
// opposite signs (and path_min_spacing = 1) make the earlier arrival a distinct
// CIR peak, so a selected path has a NEGATIVE delay relative to the detected
// origin and i_hat must cover it.
//
// Honest scope note: the pre-fix `union_lo = floor(tau_abs[0])` could not be
// made to differ from the fixed value on any geometry reachable through this
// API -- the mainlobe-spaced CIR peak selection makes the strongest arrival the
// earliest selected peak (so tau_abs[0] == min tau), and the later
// `min(union_lo, sub_lo)` clamp masks the rest.  This is therefore a low-edge
// coverage/regression guard, not a reproduction of the old line's failure.
BOOST_AUTO_TEST_CASE(test_sic_core_union_low_edge_negative_delay)
{
    const std::vector<Path> paths = { { 0.0, cplx(1.f, 0.f) },
                                      { 3.0, cplx(-0.6f, 0.f) } };
    Fixture f = make_fixture(10, 32, static_cast<int64_t>(kPre), 64, 64, 4, 8, 8,
                             100);
    f.cfg.path_min_spacing = 1;
    std::string err;
    BOOST_REQUIRE_MESSAGE(
        sic::prepare_sic_core(f.cfg, f.model.sync.data(), f.model.sync.size(),
                              f.model.preamble.data(), f.model.preamble.size(),
                              f.scratch, &err),
        "union-low-edge prepare failed: " << err);
    Signal s = build_signal(f.model, f.n, f.comm_start, paths, 0.0, kQaNoise, 61);
    SicResult r = run(f, s);
    double tmin = r.taus[0];
    for (size_t k = 1; k < r.n_taus; ++k)
        tmin = std::min(tmin, r.taus[k]);
    std::printf("[sic-qa] union-low-edge state=%s ds=%lld np=%zu tmin=%.4f "
                "ihat[floor(tmin)]=%s\n",
                state_name(r.state), static_cast<long long>(r.detected_start),
                r.n_taus, tmin,
                f.ihat[static_cast<size_t>(std::floor(tmin))] == cplx(0.f, 0.f)
                    ? "zero"
                    : "nonzero");
    for (size_t k = 0; k < r.n_taus; ++k)
        std::printf("[sic-qa] union-low-edge   tau[%zu]=%.4f\n", k, r.taus[k]);
    BOOST_REQUIRE_EQUAL(static_cast<int>(r.state),
                        static_cast<int>(SicState::Committed));
    BOOST_REQUIRE_GT(r.n_taus, size_t(1));
    // A selected path has a negative delay relative to the detected origin.
    BOOST_REQUIRE_LT(tmin, static_cast<double>(r.detected_start));
    // The reconstruction buffer must cover it (F7: union_lo = min_k floor(tau_k)).
    BOOST_CHECK(f.ihat[static_cast<size_t>(std::floor(tmin))] != cplx(0.f, 0.f));
}

// ---------------------------------------------------------------------------
// 18. energy_prefix fallback + empty-prefix prepare (F3)
// ---------------------------------------------------------------------------
// prepare_sic_core sizes the |y|^2 prefix from the ROI it is given.  A runtime
// ROI that reaches past it must fall back to the per-lag VOLK self-dot and still
// produce the SAME detection as a run whose prefix covers the whole search; and
// preparing with roi 0,0 (prefix disabled) with a full-window runtime ROI must
// agree with it too.
BOOST_AUTO_TEST_CASE(test_sic_core_energy_prefix_fallback)
{
    const std::vector<Path> paths = { { 0.0, cplx(1.f, 0.f) },
                                      { 7.0, cplx(0.f, 0.5f) } };

    // (a) reference: prepared with the WIDE roi, run with the same wide roi.
    Fixture fw = make_fixture(10, 32, static_cast<int64_t>(kPre), 64, 64, 4, 8, 8,
                              100);
    Signal s = build_signal(fw.model, fw.n, fw.comm_start, paths, 0.0, kQaNoise, 55);
    SicResult rw = run(fw, s);

    // (b) prepared with a NARROW roi (tiny prefix), run with the WIDE runtime roi.
    Fixture fn = make_fixture(10, 32, static_cast<int64_t>(kPre), 64, 64, 4, 8, 8,
                              100);
    SicConfig narrow = fn.cfg;
    narrow.roi_lo = fn.comm_start - 4;
    narrow.roi_hi = fn.comm_start + 4;
    std::string err;
    BOOST_REQUIRE_MESSAGE(
        sic::prepare_sic_core(narrow, fn.model.sync.data(), fn.model.sync.size(),
                              fn.model.preamble.data(), fn.model.preamble.size(),
                              fn.scratch, &err),
        "narrow prepare failed: " << err);
    SicResult rn = run(fn, s); // fn.cfg still holds the WIDE roi

    // (c) prepared with roi 0,0 (EMPTY prefix), run with the full-window roi.
    Fixture fe = make_fixture(10, 32, static_cast<int64_t>(kPre), 64, 64, 4, 8, 8,
                              100);
    SicConfig empty = fe.cfg;
    empty.roi_lo = 0;
    empty.roi_hi = 0;
    BOOST_REQUIRE_MESSAGE(
        sic::prepare_sic_core(empty, fe.model.sync.data(), fe.model.sync.size(),
                              fe.model.preamble.data(), fe.model.preamble.size(),
                              fe.scratch, &err),
        "empty prepare failed: " << err);
    fe.cfg.roi_lo = 0;
    fe.cfg.roi_hi = 0;
    SicResult re = run(fe, s);

    // (d) prefix sized for the wide roi but a FULL-WINDOW runtime roi.
    Fixture fm = make_fixture(10, 32, static_cast<int64_t>(kPre), 64, 64, 4, 8, 8,
                              100);
    fm.cfg.roi_lo = 0;
    fm.cfg.roi_hi = 0;
    SicResult rm = run(fm, s);

    std::printf("[sic-qa] prefix-fallback wide: ds=%lld coarse=%llu fine=%llu np=%zu "
                "| narrow-prep wide-run: ds=%lld coarse=%llu fine=%llu np=%zu | "
                "empty-prep full: ds=%lld coarse=%llu np=%zu | wide-prep full: "
                "ds=%lld coarse=%llu np=%zu\n",
                static_cast<long long>(rw.detected_start),
                static_cast<unsigned long long>(rw.coarse_candidates),
                static_cast<unsigned long long>(rw.fine_candidates), rw.n_paths,
                static_cast<long long>(rn.detected_start),
                static_cast<unsigned long long>(rn.coarse_candidates),
                static_cast<unsigned long long>(rn.fine_candidates), rn.n_paths,
                static_cast<long long>(re.detected_start),
                static_cast<unsigned long long>(re.coarse_candidates), re.n_paths,
                static_cast<long long>(rm.detected_start),
                static_cast<unsigned long long>(rm.coarse_candidates), rm.n_paths);

    // (b) must reproduce (a) exactly: same detection, same candidate bookkeeping.
    // First prove the fallback is really exercised: the narrow-prepared prefix
    // must not reach the wide runtime ROI's search extent, and the empty prepare
    // must have produced no prefix at all.
    BOOST_REQUIRE(!fn.scratch.energy_prefix.empty());
    BOOST_REQUIRE(!fw.scratch.energy_prefix.empty());
    BOOST_CHECK_LT(fn.scratch.energy_prefix.size(), fw.scratch.energy_prefix.size());
    BOOST_CHECK_LT(fn.scratch.energy_prefix.size() - 1,
                   static_cast<size_t>(fn.cfg.roi_hi - 1) + fn.scratch.sync_len);
    BOOST_CHECK(fe.scratch.energy_prefix.empty());
    BOOST_CHECK_EQUAL(rn.detected_start, rw.detected_start);
    BOOST_CHECK_EQUAL(rn.coarse_candidates, rw.coarse_candidates);
    BOOST_CHECK_EQUAL(rn.fine_candidates, rw.fine_candidates);
    BOOST_CHECK_EQUAL(rn.correlations, rw.correlations);
    BOOST_CHECK_EQUAL(rn.n_paths, rw.n_paths);
    BOOST_CHECK_EQUAL(static_cast<int>(rn.state), static_cast<int>(rw.state));
    // (b) and (c): the two runs that actually consult the fallback (all lags in
    // (c/the tail of (b)) must agree with each other on the full window.
    BOOST_CHECK_EQUAL(re.detected_start, rm.detected_start);
    BOOST_CHECK_EQUAL(re.coarse_candidates, rm.coarse_candidates);
    BOOST_CHECK_EQUAL(re.n_paths, rm.n_paths);
    BOOST_CHECK_EQUAL(static_cast<int>(re.state), static_cast<int>(SicState::Committed));
}




// ---------------------------------------------------------------------------
// 17. reconstruction window low edge for a negative relative delay (F7)
// ---------------------------------------------------------------------------
// path_select returns paths magnitude-sorted, so tau_abs[0] is not necessarily
// the smallest delay; the reconstruction window must start at the earliest
// SELECTED delay (union_lo = min_k floor(tau_k)), matching the reference, which
// builds i_hat over the full window.  Two paths a few samples apart with
// opposite signs (and path_min_spacing = 1) make the earlier arrival a distinct
// CIR peak, so a selected path has a NEGATIVE delay relative to the detected
// origin and i_hat must cover it.
//
// Honest scope note: the pre-fix `union_lo = floor(tau_abs[0])` could not be
// made to differ from the fixed value on any geometry reachable through this
// API -- the mainlobe-spaced CIR peak selection makes the strongest arrival the
// earliest selected peak (so tau_abs[0] == min tau), and the later
// `min(union_lo, sub_lo)` clamp masks the rest.  This is therefore a low-edge
// coverage/regression guard, not a reproduction of the old line's failure.
BOOST_AUTO_TEST_CASE(test_sic_core_union_low_edge_negative_delay)
{
    const std::vector<Path> paths = { { 0.0, cplx(1.f, 0.f) },
                                      { 3.0, cplx(-0.6f, 0.f) } };
    Fixture f = make_fixture(10, 32, static_cast<int64_t>(kPre), 64, 64, 4, 8, 8,
                             100);
    f.cfg.path_min_spacing = 1;
    std::string err;
    BOOST_REQUIRE_MESSAGE(
        sic::prepare_sic_core(f.cfg, f.model.sync.data(), f.model.sync.size(),
                              f.model.preamble.data(), f.model.preamble.size(),
                              f.scratch, &err),
        "union-low-edge prepare failed: " << err);
    Signal s = build_signal(f.model, f.n, f.comm_start, paths, 0.0, kQaNoise, 61);
    SicResult r = run(f, s);
    double tmin = r.taus[0];
    for (size_t k = 1; k < r.n_taus; ++k)
        tmin = std::min(tmin, r.taus[k]);
    std::printf("[sic-qa] union-low-edge state=%s ds=%lld np=%zu tmin=%.4f "
                "ihat[floor(tmin)]=%s\n",
                state_name(r.state), static_cast<long long>(r.detected_start),
                r.n_taus, tmin,
                f.ihat[static_cast<size_t>(std::floor(tmin))] == cplx(0.f, 0.f)
                    ? "zero"
                    : "nonzero");
    for (size_t k = 0; k < r.n_taus; ++k)
        std::printf("[sic-qa] union-low-edge   tau[%zu]=%.4f\n", k, r.taus[k]);
    BOOST_REQUIRE_EQUAL(static_cast<int>(r.state),
                        static_cast<int>(SicState::Committed));
    BOOST_REQUIRE_GT(r.n_taus, size_t(1));
    // A selected path has a negative delay relative to the detected origin.
    BOOST_REQUIRE_LT(tmin, static_cast<double>(r.detected_start));
    // The reconstruction buffer must cover it (F7: union_lo = min_k floor(tau_k)).
    BOOST_CHECK(f.ihat[static_cast<size_t>(std::floor(tmin))] != cplx(0.f, 0.f));
}

// ---------------------------------------------------------------------------
// 18. energy_prefix fallback + empty-prefix prepare (F3)
// ---------------------------------------------------------------------------
// prepare_sic_core sizes the |y|^2 prefix from the ROI it is given.  A runtime
// ROI that reaches past it must fall back to the per-lag VOLK self-dot and still
// produce the SAME detection as a run whose prefix covers the whole search; and
// preparing with roi 0,0 (prefix disabled) with a full-window runtime ROI must
// agree with it too.
BOOST_AUTO_TEST_CASE(test_sic_core_energy_prefix_fallback)
{
    const std::vector<Path> paths = { { 0.0, cplx(1.f, 0.f) },
                                      { 7.0, cplx(0.f, 0.5f) } };

    // (a) reference: prepared with the WIDE roi, run with the same wide roi.
    Fixture fw = make_fixture(10, 32, static_cast<int64_t>(kPre), 64, 64, 4, 8, 8,
                              100);
    Signal s = build_signal(fw.model, fw.n, fw.comm_start, paths, 0.0, kQaNoise, 55);
    SicResult rw = run(fw, s);

    // (b) prepared with a NARROW roi (tiny prefix), run with the WIDE runtime roi.
    Fixture fn = make_fixture(10, 32, static_cast<int64_t>(kPre), 64, 64, 4, 8, 8,
                              100);
    SicConfig narrow = fn.cfg;
    narrow.roi_lo = fn.comm_start - 4;
    narrow.roi_hi = fn.comm_start + 4;
    std::string err;
    BOOST_REQUIRE_MESSAGE(
        sic::prepare_sic_core(narrow, fn.model.sync.data(), fn.model.sync.size(),
                              fn.model.preamble.data(), fn.model.preamble.size(),
                              fn.scratch, &err),
        "narrow prepare failed: " << err);
    SicResult rn = run(fn, s); // fn.cfg still holds the WIDE roi

    // (c) prepared with roi 0,0 (EMPTY prefix), run with the full-window roi.
    Fixture fe = make_fixture(10, 32, static_cast<int64_t>(kPre), 64, 64, 4, 8, 8,
                              100);
    SicConfig empty = fe.cfg;
    empty.roi_lo = 0;
    empty.roi_hi = 0;
    BOOST_REQUIRE_MESSAGE(
        sic::prepare_sic_core(empty, fe.model.sync.data(), fe.model.sync.size(),
                              fe.model.preamble.data(), fe.model.preamble.size(),
                              fe.scratch, &err),
        "empty prepare failed: " << err);
    fe.cfg.roi_lo = 0;
    fe.cfg.roi_hi = 0;
    SicResult re = run(fe, s);

    // (d) prefix sized for the wide roi but a FULL-WINDOW runtime roi.
    Fixture fm = make_fixture(10, 32, static_cast<int64_t>(kPre), 64, 64, 4, 8, 8,
                              100);
    fm.cfg.roi_lo = 0;
    fm.cfg.roi_hi = 0;
    SicResult rm = run(fm, s);

    std::printf("[sic-qa] prefix-fallback wide: ds=%lld coarse=%llu fine=%llu np=%zu "
                "| narrow-prep wide-run: ds=%lld coarse=%llu fine=%llu np=%zu | "
                "empty-prep full: ds=%lld coarse=%llu np=%zu | wide-prep full: "
                "ds=%lld coarse=%llu np=%zu\n",
                static_cast<long long>(rw.detected_start),
                static_cast<unsigned long long>(rw.coarse_candidates),
                static_cast<unsigned long long>(rw.fine_candidates), rw.n_paths,
                static_cast<long long>(rn.detected_start),
                static_cast<unsigned long long>(rn.coarse_candidates),
                static_cast<unsigned long long>(rn.fine_candidates), rn.n_paths,
                static_cast<long long>(re.detected_start),
                static_cast<unsigned long long>(re.coarse_candidates), re.n_paths,
                static_cast<long long>(rm.detected_start),
                static_cast<unsigned long long>(rm.coarse_candidates), rm.n_paths);

    // (b) must reproduce (a) exactly: same detection, same candidate bookkeeping.
    // First prove the fallback is really exercised: the narrow-prepared prefix
    // must not reach the wide runtime ROI's search extent, and the empty prepare
    // must have produced no prefix at all.
    BOOST_REQUIRE(!fn.scratch.energy_prefix.empty());
    BOOST_REQUIRE(!fw.scratch.energy_prefix.empty());
    BOOST_CHECK_LT(fn.scratch.energy_prefix.size(), fw.scratch.energy_prefix.size());
    BOOST_CHECK_LT(fn.scratch.energy_prefix.size() - 1,
                   static_cast<size_t>(fn.cfg.roi_hi - 1) + fn.scratch.sync_len);
    BOOST_CHECK(fe.scratch.energy_prefix.empty());
    BOOST_CHECK_EQUAL(rn.detected_start, rw.detected_start);
    BOOST_CHECK_EQUAL(rn.coarse_candidates, rw.coarse_candidates);
    BOOST_CHECK_EQUAL(rn.fine_candidates, rw.fine_candidates);
    BOOST_CHECK_EQUAL(rn.correlations, rw.correlations);
    BOOST_CHECK_EQUAL(rn.n_paths, rw.n_paths);
    BOOST_CHECK_EQUAL(static_cast<int>(rn.state), static_cast<int>(rw.state));
    // (b) and (c): the two runs that actually consult the fallback (all lags in
    // (c/the tail of (b)) must agree with each other on the full window.
    BOOST_CHECK_EQUAL(re.detected_start, rm.detected_start);
    BOOST_CHECK_EQUAL(re.coarse_candidates, rm.coarse_candidates);
    BOOST_CHECK_EQUAL(re.n_paths, rm.n_paths);
    BOOST_CHECK_EQUAL(static_cast<int>(re.state), static_cast<int>(SicState::Committed));
}



// ---------------------------------------------------------------------------
// 18. golden cross-check (optional; skipped when the directory is absent)
// ---------------------------------------------------------------------------
BOOST_AUTO_TEST_CASE(test_sic_core_golden_crosscheck)
{
    const std::string root = golden_root();
    if (root.empty() || !dir_exists(root)) {
        std::printf("[sic-qa] SKIP golden cross-check: '%s' not present\n",
                    root.c_str());
        return;
    }
    DIR* d = ::opendir(root.c_str());
    if (!d) {
        std::printf("[sic-qa] SKIP golden cross-check: cannot open '%s'\n",
                    root.c_str());
        return;
    }
    size_t cases = 0;
    while (struct dirent* e = ::readdir(d)) {
        const std::string name = e->d_name;
        if (name == "." || name == "..")
            continue;
        const std::string cdir = root + "/" + name;
        if (!dir_exists(cdir))
            continue;
        const std::string npz_path = cdir + "/io.npz";
        const std::string meta_path = cdir + "/meta.json";
        std::vector<uint8_t> z;
        std::vector<uint8_t> mt;
        if (!read_file(npz_path, z) || !read_file(meta_path, mt)) {
            std::printf("[sic-qa] SKIP golden case '%s': io.npz/meta.json missing\n",
                        name.c_str());
            continue;
        }
        const std::string meta(reinterpret_cast<const char*>(mt.data()), mt.size());
        std::vector<cplx> y, sync, preamble, ihat_exp, out_exp, i_true;
        auto load = [&](const char* key, std::vector<cplx>& dst) -> bool {
            std::vector<uint8_t> b;
            if (!npz_get(z, std::string(key) + ".npy", b))
                return false;
            return npy_complex(b, dst);
        };
        BOOST_REQUIRE_MESSAGE(load("y", y), name << ": cannot load y from io.npz");
        BOOST_REQUIRE_MESSAGE(load("sync", sync), name << ": cannot load sync");
        BOOST_REQUIRE_MESSAGE(load("preamble", preamble),
                              name << ": cannot load preamble");
        const bool have_ihat = load("i_hat_expected", ihat_exp);
        const bool have_out = load("out_expected", out_exp);
        const bool have_i = load("i", i_true);

        double v = 0.0;
        SicConfig cfg;
        cfg.mode = SicMode::Estimate; // golden cases are all Estimate
        if (json_number(meta, "samples_per_symbol", v))
            cfg.samples_per_symbol = static_cast<size_t>(v);
        if (json_number(meta, "sync_reps", v))
            cfg.sync_reps = static_cast<size_t>(v);
        if (json_number(meta, "k_paths", v))
            cfg.k_paths = static_cast<size_t>(v);
        if (json_number(meta, "fit_reps", v))
            cfg.fit_reps = static_cast<size_t>(v);
        if (json_number(meta, "validation_reps", v))
            cfg.validation_reps = static_cast<size_t>(v);
        if (json_number(meta, "roi_lo", v))
            cfg.roi_lo = static_cast<int64_t>(v);
        if (json_number(meta, "roi_hi", v))
            cfg.roi_hi = static_cast<int64_t>(v);
        if (json_number(meta, "coarse_stride", v))
            cfg.coarse_stride = static_cast<size_t>(v);
        if (json_number(meta, "path_min_spacing", v))
            cfg.path_min_spacing = static_cast<size_t>(v);
        if (json_number(meta, "post_tail", v))
            cfg.post_tail = static_cast<size_t>(v);
        if (json_number(meta, "sample_rate", v))
            cfg.sample_rate = v;
        bool b = false;
        if (json_bool(meta, "enable_fractional", b))
            cfg.enable_fractional = b;
        if (json_bool(meta, "enable_cfo", b))
            cfg.enable_cfo = b;
        if (json_number(meta, "detect_threshold", v))
            cfg.detect_threshold = v;
        if (json_number(meta, "validate_threshold", v))
            cfg.validate_threshold = v;

        // Tolerances: explicit keys win; fall back to the README guidance.
        double tol_ihat = 1e-3, tol_out = 1e-3, tol_ds = 1.0;
        double estimate_nmse_max = -1.0, suppression_min_db = -1.0;
        double expected_ds = -1.0;
        json_number(meta, "tol_nmse_ihat", tol_ihat);
        json_number(meta, "tol_max_abs_out", tol_out);
        json_number(meta, "detected_start_tol", tol_ds);
        json_number(meta, "estimate_nmse_max", estimate_nmse_max);
        json_number(meta, "suppression_min_db", suppression_min_db);
        json_number(meta, "detected_start", expected_ds);
        const bool require_commit =
            json_bool(meta, "require_commit", b) ? b : false;

        SicScratch scratch;
        std::string err;
        BOOST_REQUIRE_MESSAGE(sic::prepare_sic_core(cfg, sync.data(), sync.size(),
                                                    preamble.data(), preamble.size(),
                                                    scratch, &err),
                              name << ": prepare failed: " << err);
        std::vector<cplx> out(y.size(), cplx(0.f, 0.f));
        std::vector<cplx> ihat(y.size(), cplx(0.f, 0.f));
        SicTemplates t;
        t.sync = sync.data();
        t.sync_len = sync.size();
        t.preamble = preamble.data();
        t.preamble_len = preamble.size();
        SicResult r;
        r.out = out.data();
        r.i_hat = ihat.data();
        const bool ok = sic::sic_one(y.data(), y.size(), t, cfg, scratch, r, nullptr);
        BOOST_REQUIRE_MESSAGE(ok, name << ": sic_one returned false");
        ++cases;
        std::printf("[sic-qa] golden '%s': state=%s detected_start=%lld np=%zu "
                    "cfo=%.1f res=%.4f i_hat=%s out=%s\n",
                    name.c_str(), state_name(r.state),
                    static_cast<long long>(r.detected_start), r.n_paths, r.cfo_hz,
                    r.residual_corr, have_ihat ? "yes" : "no",
                    have_out ? "yes" : "no");
        if (require_commit)
            BOOST_CHECK_EQUAL(static_cast<int>(r.state),
                              static_cast<int>(SicState::Committed));
        if (expected_ds >= 0.0)
            BOOST_CHECK_LE(std::abs(static_cast<double>(r.detected_start) -
                                    expected_ds),
                           tol_ds);
        if (have_i && estimate_nmse_max >= 0.0) {
            const double ne = nmse(i_true, ihat, 0, y.size());
            const double sup = 10.0 * std::log10(1.0 / std::max(ne, 1e-30));
            std::printf("[sic-qa] golden '%s': NMSE(i,my_ihat)=%.3e "
                        "suppression=%.2f dB (max %.3e)\n",
                        name.c_str(), ne, sup, estimate_nmse_max);
            BOOST_CHECK_LE(ne, estimate_nmse_max);
            if (suppression_min_db >= 0.0)
                BOOST_CHECK_GE(sup, suppression_min_db);
        }
        if (have_ihat) {
            const double ne = nmse(ihat_exp, ihat, 0, ihat.size());
            std::printf("[sic-qa] golden '%s': i_hat vs reference NMSE=%.3e "
                        "(tol %.3e)\n",
                        name.c_str(), ne, tol_ihat);
            BOOST_CHECK_LE(ne, tol_ihat);
        }
        // F1: direct selection cross-check.  The reference emits its selected
        // ABSOLUTE fractional delays as expected.taus; every reference tau must be
        // matched by a core tau within 0.02 sample (one 0.05 grid step away fails).
        // For a DECLARED stress case (generator and estimator use different
        // band-limited kernels) the core may legitimately select extra paths, so
        // only the reference->core direction is required, with a looser bound.
        {
            std::vector<double> ref_taus;
            bool stress = false;
            json_bool(meta, "declared_stress", stress);
            const double tau_tol = stress ? 0.2 : 0.02;
            if (json_number_array(meta, "taus", ref_taus) && !ref_taus.empty()) {
                double worst = 0.0;
                for (double rt : ref_taus) {
                    double best = 1e30;
                    for (size_t k = 0; k < r.n_taus; ++k)
                        best = std::min(best, std::abs(r.taus[k] - rt));
                    worst = std::max(worst, best);
                    BOOST_CHECK_MESSAGE(best <= tau_tol,
                                        name << ": reference tau " << rt
                                             << " not matched (nearest core tau off by "
                                             << best << ")");
                }
                if (!stress) {
                    BOOST_CHECK_EQUAL(r.n_taus, ref_taus.size());
                    for (size_t k = 0; k < r.n_taus; ++k) {
                        double best = 1e30;
                        for (double rt : ref_taus)
                            best = std::min(best, std::abs(r.taus[k] - rt));
                        worst = std::max(worst, best);
                        BOOST_CHECK_MESSAGE(best <= tau_tol,
                                            name << ": core tau " << r.taus[k]
                                                 << " has no reference match (off by "
                                                 << best << ")");
                    }
                }
                std::printf("[sic-qa] golden '%s': taus vs reference: %zu ref / %zu "
                            "core, max nearest-distance=%.3e (tol %.2g%s)\n",
                            name.c_str(), ref_taus.size(), r.n_taus, worst, tau_tol,
                            stress ? ", declared stress" : "");
            }
        }
        if (have_out) {
            // out = y - i_hat, so comparing out is equivalent to comparing
            // i_hat; use NMSE as the reference README recommends.  Also require
            // out == y byte-for-byte everywhere the reference left it unchanged.
            const double ne = nmse(out_exp, out, 0, out.size());
            size_t outside = 0;
            for (size_t k = 0; k < y.size(); ++k) {
                if (out_exp[k] != y[k]) {
                    continue; // inside the reference mask
                }
                ++outside;
                BOOST_CHECK_EQUAL(out[k], y[k]);
            }
            std::printf("[sic-qa] golden '%s': out vs reference NMSE=%.3e "
                        "(tol %.3e), %zu samples outside mask byte-exact\n",
                        name.c_str(), ne, tol_out, outside);
            BOOST_CHECK_LE(ne, tol_out);
        }
    }
    ::closedir(d);
    std::printf("[sic-qa] golden cross-check: %zu case(s) executed\n", cases);
}
